//! SQLite state store at `.redom/redo-msh.db`.
//!
//! Journal mode is chosen per filesystem: WAL (many readers + one writer, the
//! parallel peer model's preferred mode) on ordinary local disks, and PERSIST
//! (rollback journal) on filesystems where WAL's shared-memory mmap cannot
//! work — WSL drvfs/9p and FUSE (see `fsguard`). `REDO_JOURNAL_MODE=wal` or
//! `=persist` overrides the detection. A database left in WAL format by a
//! build on another filesystem is converted transparently on open.
//!
//! Two tables (see plan):
//!   * `files` — per-file stamp cache for *all* files (sources and targets).
//!     Equality is always by `csum` (blake3); `mtime`/`size` only gate whether
//!     we must recompute the hash.
//!   * `deps`  — dependency edges. The `csum` recorded here is the equality
//!     basis for change detection; `mtime`/`size` are fast-path accelerators.
//!
//! A `meta` table holds the schema version and the monotonic `runid` build
//! counter (clock-independent), and the session-wide overwrite decisions.
//!
//! The shared waits-for graph (which turns a dependency cycle between
//! concurrent builds into an error instead of a deadlock) is NOT here: it
//! is transient, so it lives in its own unsynced database (see `waits.rs`).
//! The `waits` table this schema still creates is unused.

use anyhow::{Context, Result};
use rusqlite::{params, Connection, OptionalExtension};
use std::path::{Path, PathBuf};
use std::time::Duration;

const BUSY_TIMEOUT: Duration = Duration::from_secs(60);

/// Bump whenever the on-disk schema changes incompatibly. The `.redom` database
/// is a pure cache (everything in it can be regenerated by rebuilding), so a
/// mismatch is resolved by wiping and rebuilding rather than migrating.
///
/// A wipe is not free, though: with no record of what redo built, existing
/// outputs that only a `default*.do` matches become static sources, and ones
/// with an exact `.do` are refused as "never built". So additive changes
/// (a nullable column, a new table) migrate in place instead of bumping this
/// (see `migrate_additive`), and a bump whose incompatibility is confined to
/// transient state upgrades in place too (see `upgrade_in_place`).
pub const SCHEMA_VERSION: i64 = 4;

/// Dependency edge kinds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(i64)]
pub enum DepKind {
    IfChange = 0,
    IfCreate = 1,
    Always = 2,
    DoFile = 3,
    /// Marker recorded when a build starts and removed only after the target
    /// commits successfully. If it is present outside a build, the last build
    /// failed (or crashed) and the target is unconditionally out of date —
    /// a leftover output file from an earlier success must not be trusted.
    Uncommitted = 4,
}

impl DepKind {
    pub fn from_i64(v: i64) -> Option<DepKind> {
        match v {
            0 => Some(DepKind::IfChange),
            1 => Some(DepKind::IfCreate),
            2 => Some(DepKind::Always),
            3 => Some(DepKind::DoFile),
            4 => Some(DepKind::Uncommitted),
            _ => None,
        }
    }
}

/// Open (creating if needed) the database and apply pragmas + schema.
///
/// If an existing database was written by a redo-msh with a different
/// `SCHEMA_VERSION`, it is wiped and recreated: the database is a regenerable
/// cache, so rebuilding is always safe (the next build just does more work
/// once). This avoids silently misreading an incompatible layout.
pub fn open(db_path: &Path) -> Result<Connection> {
    let mut span = crate::profile::span("db.open", "");
    let mode = choose_journal_mode(db_path);
    span.detail(|| format!("journal mode {mode:?}"));
    if mode == JournalMode::Persist {
        // A WAL-format database cannot even be read here (its shared-memory
        // map fails), so this must happen before the version probe below.
        convert_from_wal_if_needed(db_path)?;
    }
    // Fast path: a database stamped by this exact schema needs no version
    // probe and no schema statements. Every redo process — and every task
    // thread — opens a connection, and on a slow filesystem the dozen
    // idempotent statements of `init_schema` (two of them writes) cost more
    // than the rest of an up-to-date check.
    if db_path.exists() {
        let conn = connect(db_path, mode)?;
        if schema_stamp(&conn) == Some(SCHEMA_STAMP) {
            return Ok(conn);
        }
        // Dropped here: the slow path may need to wipe the file.
    }
    if let Some(found) = incompatible_version(db_path)? {
        if !upgrade_in_place(db_path, found)? {
            eprintln!(
                "redo-msh: .redom database schema v{found} != v{SCHEMA_VERSION}; \
                 rebuilding build state"
            );
            wipe(db_path);
        }
    }
    let conn = connect(db_path, mode)?;
    init_schema(&conn)?;
    // Stamp last: only a database on which every statement above succeeded
    // may skip them. Racing initializers all write the same value.
    conn.pragma_update(None, "user_version", SCHEMA_STAMP)?;
    Ok(conn)
}

/// The value of `PRAGMA user_version` on a database whose schema is exactly
/// what this binary's `init_schema` produces. It combines `SCHEMA_VERSION`
/// with a revision of the additive migrations: **bump `ADDITIVE_REV` whenever
/// `init_schema` or `migrate_additive` gains a statement**, or databases
/// stamped by the previous binary will never receive it.
///
/// Binaries from before the stamp ignore it. They cannot invalidate it
/// either: on a version mismatch they wipe the file (the stamp goes with
/// it), and their own schema statements are a subset of ours. An in-place
/// upgrade from a *stamped* older schema must clear the stamp itself.
const ADDITIVE_REV: i64 = 1;
const SCHEMA_STAMP: i64 = SCHEMA_VERSION * 1000 + ADDITIVE_REV;

fn schema_stamp(conn: &Connection) -> Option<i64> {
    conn.query_row("PRAGMA user_version", [], |r| r.get(0)).ok()
}

/// Open a connection and apply the per-connection settings (no schema work).
fn connect(db_path: &Path, mode: JournalMode) -> Result<Connection> {
    let mut conn = Connection::open(db_path)
        .with_context(|| format!("opening database {}", db_path.display()))?;
    if crate::profile::enabled() {
        conn.profile(Some(crate::profile::sql_hook));
    }
    apply_pragmas(&conn, mode)?;
    Ok(conn)
}

/// Journal mode for the state database. WAL is preferred (readers and the
/// writer never block each other); PERSIST is the fallback for filesystems
/// where WAL's `-shm` mmap cannot work.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum JournalMode {
    Wal,
    Persist,
}

/// Pick the journal mode for `db_path`: `REDO_JOURNAL_MODE` if set (an escape
/// hatch, and the way to exercise the PERSIST path in tests on any FS),
/// otherwise by classifying the filesystem under the database's directory.
/// A pure function of environment + path, so every concurrent redo-msh
/// process computes the same answer for the same database.
pub fn choose_journal_mode(db_path: &Path) -> JournalMode {
    if let Ok(v) = std::env::var("REDO_JOURNAL_MODE") {
        match v.to_ascii_lowercase().as_str() {
            "wal" => return JournalMode::Wal,
            "persist" => return JournalMode::Persist,
            _ => eprintln!(
                "redo-msh: warning: ignoring REDO_JOURNAL_MODE={v:?} \
                 (expected 'wal' or 'persist')"
            ),
        }
    }
    // Cached per process: every task thread opens its own connection, and
    // the filesystem under one database does not change mid-run.
    static KIND: std::sync::OnceLock<crate::fsguard::FsKind> = std::sync::OnceLock::new();
    let dir = db_path.parent().unwrap_or_else(|| Path::new("."));
    match KIND.get_or_init(|| crate::fsguard::classify(dir)) {
        crate::fsguard::FsKind::MmapUnsafe => JournalMode::Persist,
        _ => JournalMode::Wal,
    }
}

/// Whether the file at `db_path` is an SQLite database whose header says it
/// is in WAL format (read/write format version 2). Read directly from the
/// header because opening a WAL database through SQLite is exactly what
/// fails on an mmap-unsafe filesystem.
pub(crate) fn is_wal_format(db_path: &Path) -> bool {
    use std::io::Read;
    let mut header = [0u8; 20];
    match std::fs::File::open(db_path).and_then(|mut f| f.read_exact(&mut header)) {
        Ok(()) => header[..16] == *b"SQLite format 3\0" && (header[18] == 2 || header[19] == 2),
        Err(_) => false,
    }
}

/// Convert a WAL-format database to rollback-journal format in place. Needed
/// when a database built on an ordinary disk moves to an mmap-unsafe
/// filesystem: WAL there fails in `xShmMap` before any query can run. With
/// `locking_mode=EXCLUSIVE` set first, SQLite runs WAL against heap-backed
/// shared memory (no `-shm` mmap), which lets the `journal_mode` change
/// checkpoint the WAL and rewrite the header. Racing processes serialize on
/// the exclusive lock; the losers then find the work already done (their
/// `journal_mode` change is a no-op).
fn convert_from_wal_if_needed(db_path: &Path) -> Result<()> {
    if !is_wal_format(db_path) {
        return Ok(());
    }
    eprintln!(
        "redo-msh: {} is in WAL format, which this filesystem cannot support; \
         converting to rollback-journal format",
        db_path.display()
    );
    let conn = Connection::open(db_path)
        .with_context(|| format!("opening database {} for conversion", db_path.display()))?;
    conn.busy_timeout(BUSY_TIMEOUT)?;
    conn.pragma_update(None, "locking_mode", "EXCLUSIVE")?;
    conn.pragma_update(None, "journal_mode", "PERSIST")
        .with_context(|| format!("converting {} out of WAL mode", db_path.display()))?;
    // Dropping the connection releases the exclusive lock.
    Ok(())
}

/// If `db_path` exists and records a schema version different from the current
/// one, return that version. Returns `None` for a fresh database, a database
/// with no recorded version, or a version match.
fn incompatible_version(db_path: &Path) -> Result<Option<i64>> {
    if !db_path.exists() {
        return Ok(None);
    }
    let conn = Connection::open(db_path)
        .with_context(|| format!("opening database {}", db_path.display()))?;
    let has_meta = conn
        .query_row(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name='meta'",
            [],
            |_| Ok(()),
        )
        .optional()?
        .is_some();
    if !has_meta {
        return Ok(None);
    }
    let version: Option<i64> = conn
        .query_row(
            "SELECT value FROM meta WHERE key = 'schema_version'",
            [],
            |r| r.get(0),
        )
        .optional()?;
    // `conn` is dropped here, releasing the file before the caller wipes it.
    Ok(match version {
        Some(v) if v != SCHEMA_VERSION => Some(v),
        _ => None,
    })
}

/// Upgrade a database of an older schema in place, where that loses nothing
/// worth keeping; `Ok(false)` means it must be wiped instead.
///
/// v2 -> v4: the only incompatible change is the `waits` table, whose v2
/// layout (lock-wait edges keyed by holder) the v4 waits-for graph replaces.
/// Its rows are transient wait edges, so dropping it is free; `init_schema`
/// then creates the v4 layout. Racing processes serialize on the immediate
/// transaction, and the version re-check inside it makes the loser a no-op
/// (it must not drop a v4 table the winner may already be using).
fn upgrade_in_place(db_path: &Path, found: i64) -> Result<bool> {
    if found != 2 {
        return Ok(false);
    }
    let mut conn = Connection::open(db_path)
        .with_context(|| format!("opening database {} for upgrade", db_path.display()))?;
    conn.busy_timeout(BUSY_TIMEOUT)?;
    let txn = conn.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)?;
    let version: Option<i64> = txn
        .query_row("SELECT value FROM meta WHERE key = 'schema_version'", [], |r| r.get(0))
        .optional()?;
    if version == Some(2) {
        txn.execute_batch("DROP TABLE IF EXISTS waits;")?;
        txn.execute(
            "UPDATE meta SET value = ?1 WHERE key = 'schema_version'",
            [SCHEMA_VERSION],
        )?;
    }
    txn.commit()?;
    Ok(true)
}

/// Remove the database and its sidecar files (both journal modes).
pub(crate) fn wipe(db_path: &Path) {
    let _ = std::fs::remove_file(db_path);
    let _ = std::fs::remove_file(sidecar(db_path, "-wal"));
    let _ = std::fs::remove_file(sidecar(db_path, "-shm"));
    let _ = std::fs::remove_file(sidecar(db_path, "-journal"));
}

fn sidecar(db_path: &Path, suffix: &str) -> PathBuf {
    let mut s = db_path.as_os_str().to_os_string();
    s.push(suffix);
    PathBuf::from(s)
}

/// The busy handler every redo connection uses (see `apply_pragmas`).
pub(crate) fn install_busy_handler(conn: &Connection) -> Result<()> {
    conn.busy_handler(Some(|count| {
        std::thread::sleep(std::time::Duration::from_micros(200));
        (count as u64) < BUSY_TIMEOUT.as_micros() as u64 / 200
    }))?;
    Ok(())
}

fn apply_pragmas(conn: &Connection, mode: JournalMode) -> Result<()> {
    // The busy handler must be set before journal_mode: the mode change
    // itself takes locks and can contend with concurrent peers. A custom
    // handler with a short fixed sleep replaces SQLite's default
    // millisecond-scale backoff: under the parallel engine many short
    // write transactions collide constantly, and paying 1-25ms per
    // collision serializes the build far below the database's actual
    // throughput. 200µs x 300k retries preserves the 60s overall budget.
    install_busy_handler(conn)?;
    match mode {
        JournalMode::Wal => {
            // WAL: many readers + one writer; preferred for the parallel peer
            // model. synchronous=NORMAL is safe in WAL: power loss can drop
            // the last commit (causing a safe rebuild) but never corrupts.
            conn.pragma_update(None, "journal_mode", "WAL")?;
            conn.pragma_update(None, "synchronous", "NORMAL")?;
        }
        JournalMode::Persist => {
            // Rollback journal for mmap-unsafe filesystems (WSL drvfs/9p,
            // FUSE). PERSIST avoids journal create/delete churn per commit.
            // synchronous must be FULL here: unlike WAL, NORMAL in rollback
            // mode leaves a window where power loss can corrupt the database.
            conn.pragma_update(None, "journal_mode", "PERSIST")?;
            conn.pragma_update(None, "synchronous", "FULL")?;
        }
    }
    conn.pragma_update(None, "foreign_keys", "ON")?;
    Ok(())
}

/// Run `f` inside an `BEGIN IMMEDIATE` transaction, committing on success and
/// rolling back on error.
///
/// All multi-statement write sequences must go through this. IMMEDIATE takes
/// the write lock up front, so lock acquisition happens at `BEGIN` — where the
/// busy timeout applies — rather than on the first write inside a read
/// transaction, where SQLite returns `SQLITE_BUSY` immediately (waiting there
/// could deadlock two upgrading readers). This matters in both journal modes
/// (WAL still has a single writer) and doubly under PERSIST, where readers
/// and the writer also contend.
#[track_caller]
pub fn write_txn<T>(conn: &Connection, f: impl FnOnce(&Connection) -> Result<T>) -> Result<T> {
    let mut span = if crate::profile::enabled() {
        let at = std::panic::Location::caller();
        crate::profile::span("db.txn", &format!("{}:{}", at.file(), at.line()))
    } else {
        crate::profile::span("db.txn", "")
    };
    let tx = rusqlite::Transaction::new_unchecked(conn, rusqlite::TransactionBehavior::Immediate)?;
    let begin_us = span.elapsed_us();
    span.detail(|| format!("write lock after {begin_us}us"));
    let out = f(&tx)?;
    tx.commit()?;
    Ok(out)
}

/// One queued write: a few statements that need no result beyond success.
/// `Fn`, not `FnOnce`: a batch that fails as a whole is retried job by job.
pub type WriteJob = Box<dyn Fn(&Connection) -> Result<()> + Send>;

/// Group commit for a process's small independent writes.
///
/// The parallel engine's task threads each issue one-statement writes
/// ("verified this run", stamp-cache refreshes, wait-edge cleanup). As
/// separate commits those serialize on the database's single write lock and
/// pay a full durable commit each — hundreds of milliseconds apiece on a
/// slow filesystem under the rollback journal, which made an up-to-date
/// check of N targets cost N commits.
///
/// Here a writer queues its job and blocks until it is committed. Whoever
/// finds no commit in progress becomes the leader: it takes everything
/// queued, runs it as ONE transaction on its own connection, and publishes
/// the results. Jobs that arrive meanwhile queue up for the next leader, so
/// the batch size adapts to exactly how slow commits are. Nothing is
/// deferred: `run` returns only after the caller's write is committed, so
/// every ordering the engine relies on (a target is marked verified before
/// its task settles, a wait edge is gone before its build starts) holds
/// exactly as with a direct write.
#[derive(Default)]
pub struct GroupCommit {
    state: std::sync::Mutex<GroupState>,
    cv: std::sync::Condvar,
}

#[derive(Default)]
struct GroupState {
    queue: Vec<(u64, WriteJob)>,
    done: std::collections::HashMap<u64, std::result::Result<(), String>>,
    leader: bool,
    next_id: u64,
}

impl GroupCommit {
    /// Commit `job`, batched with any other writes queued in this process.
    /// `conn` is the caller's connection, used if the caller ends up leading.
    pub fn run(&self, conn: &Connection, job: WriteJob) -> Result<()> {
        // Inside an open transaction the write simply joins it (and a
        // nested BEGIN would fail).
        if !conn.is_autocommit() {
            return job(conn);
        }
        let mut st = self.state.lock().unwrap();
        let id = st.next_id;
        st.next_id += 1;
        st.queue.push((id, job));
        loop {
            if let Some(res) = st.done.remove(&id) {
                return res.map_err(|m| anyhow::anyhow!(m));
            }
            if st.leader {
                st = self.cv.wait(st).unwrap();
                continue;
            }
            // No commit in progress and our job is not done, so it is still
            // queued: lead, and it is in the batch we take.
            st.leader = true;
            let batch = std::mem::take(&mut st.queue);
            drop(st);
            // Leadership is handed back on every exit, including a panic in
            // a job: followers wait without a timeout.
            let mut handback = Handback { group: self, results: Vec::new(), ids: Vec::new() };
            handback.ids = batch.iter().map(|(id, _)| *id).collect();
            handback.results = commit_batch(conn, &batch);
            drop(handback);
            st = self.state.lock().unwrap();
        }
    }
}

struct Handback<'a> {
    group: &'a GroupCommit,
    ids: Vec<u64>,
    results: Vec<std::result::Result<(), String>>,
}

impl Drop for Handback<'_> {
    fn drop(&mut self) {
        let mut st = self.group.state.lock().unwrap_or_else(|e| e.into_inner());
        st.leader = false;
        let mut results = std::mem::take(&mut self.results).into_iter();
        for id in &self.ids {
            let res = results
                .next()
                .unwrap_or_else(|| Err("internal error: write batch panicked".to_string()));
            st.done.insert(*id, res);
        }
        self.group.cv.notify_all();
    }
}

/// Run a batch as one transaction. If that fails, the batch is rolled back
/// and each job gets its own transaction, so one bad write cannot fail (or
/// be blamed on) its neighbours.
fn commit_batch(conn: &Connection, batch: &[(u64, WriteJob)]) -> Vec<std::result::Result<(), String>> {
    let mut span = crate::profile::span("db.group", "");
    span.detail(|| format!("{} writes in one commit", batch.len()));
    let whole = write_txn(conn, |c| {
        for (_, job) in batch {
            job(c)?;
        }
        Ok(())
    });
    match whole {
        Ok(()) => batch.iter().map(|_| Ok(())).collect(),
        Err(e) if batch.len() == 1 => vec![Err(format!("{e:#}"))],
        Err(_) => batch
            .iter()
            .map(|(_, job)| write_txn(conn, |c| job(c)).map_err(|e| format!("{e:#}")))
            .collect(),
    }
}

fn init_schema(conn: &Connection) -> Result<()> {
    conn.execute_batch(
        r#"
        CREATE TABLE IF NOT EXISTS meta (
            key   TEXT PRIMARY KEY,
            value INTEGER NOT NULL
        );

        -- Path columns use COLLATE NOCASE so identity is case-insensitive,
        -- matching NTFS semantics and keeping one row per file when a project
        -- is shared between Windows and WSL. Original case is preserved in the
        -- stored text (used for filesystem I/O); only comparison is folded.
        CREATE TABLE IF NOT EXISTS files (
            path     TEXT PRIMARY KEY COLLATE NOCASE, -- root-relative, '/' separators
            dofile   TEXT,               -- .do file used (root-relative); NULL = source file
            built_at INTEGER,            -- unix nanos of last successful build (targets only)
            mtime    INTEGER,            -- last-observed mtime (unix nanos)
            size     INTEGER,            -- last-observed size in bytes
            csum     TEXT,               -- last-observed blake3 content hash (hex)
            runid    INTEGER,            -- build counter when last verified/built
            hashed_at INTEGER            -- unix nanos when csum was computed
        );

        CREATE TABLE IF NOT EXISTS deps (
            target TEXT NOT NULL COLLATE NOCASE, -- dependent target (root-relative)
            kind   INTEGER NOT NULL,     -- DepKind: 0 ifchange, 1 ifcreate, 2 always, 3 dofile, 4 uncommitted
            dep    TEXT COLLATE NOCASE,  -- dependency path (ifchange/ifcreate/dofile); NULL for always
            csum   TEXT,                 -- dep content hash expected at build time (equality basis)
            mtime  INTEGER,              -- recorded mtime (fast-path accelerator)
            size   INTEGER,              -- recorded size (fast-path accelerator)
            PRIMARY KEY (target, kind, dep)
        );

        CREATE INDEX IF NOT EXISTS deps_by_target ON deps(target);

        -- UNUSED since the waits-for graph moved to its own database
        -- (`.redom/waits.db`, see waits.rs); kept so binaries from before
        -- the move, which still use it here, find the layout they expect.
        -- The shared waits-for graph (see waits.rs), implementing the
        -- machine verified in verification/SpeculationMP.tla: one row per
        -- live wait edge "some traversal of `waiter` is blocked until
        -- `dep` settles". Every settle-wait is here (rule R1) — checker
        -- waits, speculative-spawn creation edges (which make drain waits
        -- visible), and running-do-file demands — and cycle detection is a
        -- reachability query run atomically with the insert. `kind` types
        -- the edge (rule R2): 0 = hard demand (a running do-file's
        -- redo-ifchange), 1 = soft checker wait, 2 = soft creation edge.
        -- Cycles that ride a soft edge are resolved by evicting the
        -- speculation, never by failing the demand (rule R3). Paths are
        -- stored pre-lowercased (the graph only needs identity, and BINARY
        -- comparison keeps the recursive CTE collation-exact). `owner`
        -- identifies the inserting process and is tied to a kernel
        -- liveness lock, so edges from dead processes can be
        -- garbage-collected. Edges are transient state, deliberately not
        -- scoped to a session: two concurrent redo invocations share the
        -- same target locks, so a cross-session wait cycle is a real
        -- deadlock and must be visible in one graph.
        CREATE TABLE IF NOT EXISTS waits (
            waiter  TEXT NOT NULL,
            dep     TEXT NOT NULL,
            owner   TEXT NOT NULL,
            kind    INTEGER NOT NULL,
            PRIMARY KEY (waiter, dep, owner)
        );

        -- Targets a user asked for by name on a top-level `redo` command
        -- line (not dependencies, not a `redo` run from inside a do-file),
        -- with when each was last asked for. Recorded before the build, so
        -- failed attempts count too. This is the only record of names that
        -- exist solely as a request — nothing on disk says what a
        -- `default*.do` is usually asked to build — and it feeds shell
        -- completion (`redo-msh requested`).
        CREATE TABLE IF NOT EXISTS requests (
            path         TEXT PRIMARY KEY COLLATE NOCASE, -- root-relative, '/' separators
            requested_at INTEGER NOT NULL                 -- unix nanos of the latest request
        );

        CREATE INDEX IF NOT EXISTS waits_by_owner ON waits(owner);
        CREATE INDEX IF NOT EXISTS waits_by_dep ON waits(dep);
        "#,
    )
    .context("initializing schema")?;

    migrate_additive(conn)?;

    conn.execute(
        "INSERT OR IGNORE INTO meta(key, value) VALUES ('schema_version', ?1)",
        [SCHEMA_VERSION],
    )?;
    conn.execute(
        "INSERT OR IGNORE INTO meta(key, value) VALUES ('runid', 0)",
        [],
    )?;
    Ok(())
}

/// Additive, backward-compatible schema changes, applied in place to databases
/// created before them (new tables come from `CREATE TABLE IF NOT EXISTS`).
/// Older binaries ignore the additions. Two processes may race to add the
/// same column; the loser's "duplicate column" error is harmless.
fn migrate_additive(conn: &Connection) -> Result<()> {
    let has_hashed_at = conn
        .prepare("SELECT 1 FROM pragma_table_info('files') WHERE name = 'hashed_at'")?
        .exists([])?;
    if !has_hashed_at {
        // NULL means "age unknown", which the racily-clean rule treats as
        // untrusted: such rows are simply re-hashed once.
        if let Err(e) = conn.execute("ALTER TABLE files ADD COLUMN hashed_at INTEGER", []) {
            if !e.to_string().contains("duplicate column") {
                return Err(anyhow::Error::new(e).context("adding files.hashed_at"));
            }
        }
    }
    Ok(())
}

/// Note that the user asked for `targets` (root-relative) at `now` (unix
/// nanos). The latest spelling's case wins, like every other path column.
pub fn record_requests(conn: &Connection, targets: &[String], now: i64) -> Result<()> {
    write_txn(conn, |tx| {
        let mut stmt = tx.prepare(
            "INSERT INTO requests(path, requested_at) VALUES (?1, ?2)
             ON CONFLICT(path) DO UPDATE SET path = excluded.path,
                                             requested_at = excluded.requested_at",
        )?;
        for t in targets {
            stmt.execute(params![t, now])?;
        }
        Ok(())
    })
}

/// Every requested target with its latest request time, most recent first.
pub fn requests(conn: &Connection) -> Result<Vec<(String, i64)>> {
    let mut stmt =
        conn.prepare("SELECT path, requested_at FROM requests ORDER BY requested_at DESC, path")?;
    let rows = stmt
        .query_map([], |r| Ok((r.get(0)?, r.get(1)?)))?
        .collect::<rusqlite::Result<_>>()?;
    Ok(rows)
}

/// The session-wide overwrite decision ("all" / "quit" at a prompt), shared
/// by EVERY process of the session through the database — the in-process
/// atomic and the child environment only reach this process and children
/// spawned later; a sibling redo already running would otherwise ask the
/// same question again. Stored in `meta` under `overwrite:<session>`; the
/// value is the caller's mode code. `None`: no decision yet.
pub fn overwrite_mode(conn: &Connection, session: i64) -> Result<Option<i64>> {
    Ok(conn
        .query_row(
            "SELECT value FROM meta WHERE key = ?1",
            params![format!("overwrite:{session}")],
            |r| r.get::<_, i64>(0),
        )
        .optional()?)
}

pub fn set_overwrite_mode(conn: &Connection, session: i64, mode: i64) -> Result<()> {
    conn.execute(
        "INSERT OR REPLACE INTO meta(key, value) VALUES (?1, ?2)",
        params![format!("overwrite:{session}"), mode],
    )?;
    Ok(())
}

/// Forget every session's overwrite decision but `keep`'s. Called at
/// top-level session start; a concurrent top-level session that had
/// answered "all" is at worst asked once more.
pub fn forget_overwrite_modes(conn: &Connection, keep: i64) -> Result<()> {
    conn.execute(
        "DELETE FROM meta WHERE key LIKE 'overwrite:%' AND key <> ?1",
        params![format!("overwrite:{keep}")],
    )?;
    Ok(())
}

/// Atomically increment and return the global build counter. A single
/// UPDATE…RETURNING statement, so two concurrent processes can never read
/// each other's increment (the old UPDATE-then-SELECT pair could).
pub fn next_runid(conn: &Connection) -> Result<i64> {
    let runid: i64 = conn.query_row(
        "UPDATE meta SET value = value + 1 WHERE key = 'runid' RETURNING value",
        [],
        |r| r.get(0),
    )?;
    Ok(runid)
}

