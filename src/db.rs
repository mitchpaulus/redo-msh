    #[test]
    fn paths_are_case_insensitive() {
        let dir = std::env::temp_dir().join(format!("redo-msh-dbtest-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let conn = open(&dir.join("t.db")).unwrap();

        conn.execute("INSERT INTO files(path) VALUES ('App.txt')", [])
            .unwrap();
        // A different-cased lookup matches (NOCASE collation).
        let found: i64 = conn
            .query_row(
                "SELECT count(*) FROM files WHERE path = ?1",
                ["app.txt"],
                |r| r.get(0),
            )
            .unwrap();
        assert_eq!(found, 1);

        // A different-cased insert collapses onto the same primary key.
        conn.execute("INSERT OR REPLACE INTO files(path) VALUES ('APP.TXT')", [])
            .unwrap();
        let total: i64 = conn
            .query_row("SELECT count(*) FROM files", [], |r| r.get(0))
            .unwrap();
        assert_eq!(total, 1, "different casings must collapse to one row");

        // Original case is preserved in storage (for filesystem I/O).
        let stored: String = conn
            .query_row("SELECT path FROM files LIMIT 1", [], |r| r.get(0))
            .unwrap();
        assert!(stored.chars().any(|c| c.is_ascii_uppercase()));

        drop(conn);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn incompatible_schema_is_rebuilt() {
        let dir = std::env::temp_dir().join(format!(
            "redo-msh-dbver-{}-{}",
            std::process::id(),
            "mismatch"
        ));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("t.db");

        // Create a database, add a row, then fake an older schema version.
        {
            let conn = open(&path).unwrap();
            conn.execute("INSERT INTO files(path) VALUES ('stale.txt')", [])
                .unwrap();
            conn.execute(
                "UPDATE meta SET value = 1 WHERE key = 'schema_version'",
                [],
            )
            .unwrap();
            // A database really written by an older schema carries no (or
            // another) stamp; ours would vouch for the current schema.
            conn.pragma_update(None, "user_version", 0).unwrap();
        }

        // Reopening detects the mismatch and rebuilds from scratch.
        let conn = open(&path).unwrap();
        let version: i64 = conn
            .query_row("SELECT value FROM meta WHERE key='schema_version'", [], |r| {
                r.get(0)
            })
            .unwrap();
        assert_eq!(version, SCHEMA_VERSION);
        let rows: i64 = conn
            .query_row("SELECT count(*) FROM files", [], |r| r.get(0))
            .unwrap();
        assert_eq!(rows, 0, "stale data must be wiped on a schema mismatch");

        drop(conn);
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// A database this binary initialized is stamped, and a stamped database
    /// is opened without re-running the schema statements; an unstamped one
    /// of the current schema (written by a binary from before the stamp) is
    /// initialized once more, keeping its data, and stamped.
    #[test]
    fn stamped_database_skips_schema_setup() {
        let dir = std::env::temp_dir().join(format!("redo-msh-stamp-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("t.db");
        {
            let conn = open(&path).unwrap();
            assert_eq!(schema_stamp(&conn), Some(SCHEMA_STAMP));
            conn.execute("INSERT INTO files(path) VALUES ('kept.txt')", []).unwrap();
            // Proof the fast path runs no schema statement: with the table
            // gone, a stamped open must not recreate it.
            conn.execute_batch("DROP TABLE requests").unwrap();
        }
        {
            let conn = open(&path).unwrap();
            assert!(conn.prepare("SELECT 1 FROM requests").is_err());
            conn.pragma_update(None, "user_version", 0).unwrap();
        }
        let conn = open(&path).unwrap();
        assert!(conn.prepare("SELECT 1 FROM requests").is_ok());
        assert_eq!(schema_stamp(&conn), Some(SCHEMA_STAMP));
        let rows: i64 = conn.query_row("SELECT count(*) FROM files", [], |r| r.get(0)).unwrap();
        assert_eq!(rows, 1);
        drop(conn);
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// Concurrent writers' jobs all commit, and each caller gets its own
    /// job's result even when a batch-mate fails.
    #[test]
    fn group_commit_commits_every_job_and_isolates_failures() {
        let dir = std::env::temp_dir().join(format!("redo-msh-group-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("t.db");
        drop(open(&path).unwrap());
        let group = std::sync::Arc::new(GroupCommit::default());
        let threads: Vec<_> = (0..16)
            .map(|i| {
                let (group, path) = (group.clone(), path.clone());
                std::thread::spawn(move || {
                    let conn = open(&path).unwrap();
                    let bad = i % 4 == 0;
                    let res = group.run(
                        &conn,
                        Box::new(move |c| {
                            if bad {
                                c.execute("INSERT INTO no_such_table VALUES (1)", [])?;
                            }
                            c.execute("INSERT INTO files(path) VALUES (?1)", [format!("f{i}")])?;
                            Ok(())
                        }),
                    );
                    assert_eq!(res.is_err(), bad, "job {i}: {res:?}");
                })
            })
            .collect();
        for t in threads {
            t.join().unwrap();
        }
        let conn = open(&path).unwrap();
        let rows: i64 = conn.query_row("SELECT count(*) FROM files", [], |r| r.get(0)).unwrap();
        assert_eq!(rows, 12);
        drop(conn);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn wal_database_converts_to_rollback_journal() {
        let dir = std::env::temp_dir().join(format!("redo-msh-walconv-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("t.db");

        // Create a WAL database with a row in it (open() defaults to WAL on
        // a normal local filesystem).
        {
            let conn = open(&path).unwrap();
            conn.execute("INSERT INTO files(path) VALUES ('kept.txt')", [])
                .unwrap();
        }
        assert!(is_wal_format(&path), "fresh db should be in WAL format");

        // Convert as the mmap-unsafe open path would, then reopen in PERSIST
        // mode: data must survive and the header must no longer say WAL.
        convert_from_wal_if_needed(&path).unwrap();
        assert!(!is_wal_format(&path), "conversion must rewrite the header");

        let conn = Connection::open(&path).unwrap();
        apply_pragmas(&conn, JournalMode::Persist).unwrap();
        let mode: String = conn
            .query_row("PRAGMA journal_mode", [], |r| r.get(0))
            .unwrap();
        assert_eq!(mode.to_ascii_lowercase(), "persist");
        let rows: i64 = conn
            .query_row("SELECT count(*) FROM files", [], |r| r.get(0))
            .unwrap();
        assert_eq!(rows, 1, "data must survive the WAL conversion");

        // Converting an already-converted database is a no-op.
        drop(conn);
        convert_from_wal_if_needed(&path).unwrap();

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn persist_mode_full_open_works() {
        let dir = std::env::temp_dir().join(format!("redo-msh-persist-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("t.db");

        let conn = Connection::open(&path).unwrap();
        apply_pragmas(&conn, JournalMode::Persist).unwrap();
        init_schema(&conn).unwrap();

        let sync: i64 = conn
            .query_row("PRAGMA synchronous", [], |r| r.get(0))
            .unwrap();
        assert_eq!(sync, 2, "PERSIST mode must run synchronous=FULL");

        assert_eq!(next_runid(&conn).unwrap(), 1);
        assert_eq!(next_runid(&conn).unwrap(), 2);

        // Session-wide overwrite decisions: per session, forgotten at the
        // next session start.
        assert_eq!(overwrite_mode(&conn, 2).unwrap(), None);
        set_overwrite_mode(&conn, 2, 1).unwrap();
        assert_eq!(overwrite_mode(&conn, 2).unwrap(), Some(1));
        set_overwrite_mode(&conn, 2, 2).unwrap();
        assert_eq!(overwrite_mode(&conn, 2).unwrap(), Some(2));
        forget_overwrite_modes(&conn, 3).unwrap();
        assert_eq!(overwrite_mode(&conn, 2).unwrap(), None);

        drop(conn);
        let _ = std::fs::remove_dir_all(&dir);
    }

